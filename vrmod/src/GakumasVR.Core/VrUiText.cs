{
    private static readonly IReadOnlyDictionary<VrUiLanguage, IReadOnlyDictionary<string, string>> Resources =
        new Dictionary<VrUiLanguage, IReadOnlyDictionary<string, string>>
        {
            [VrUiLanguage.Korean] = Korean(), [VrUiLanguage.English] = English(), [VrUiLanguage.Japanese] = Japanese()
        };
    public static string Get(VrUiLanguage language, string key) => Resources[language].TryGetValue(key, out string? value)
        ? value : throw new InvalidOperationException($"Missing UI text: {language}/{key}");
    public static string Format(VrUiLanguage language, string key, params object[] arguments) =>
        string.Format(CultureInfo.GetCultureInfo(VrUiPreferences.Code(language)), Get(language, key), arguments);
    public static void Validate()
    {
        var reference = new HashSet<string>(Resources[VrUiLanguage.Korean].Keys, StringComparer.Ordinal);
        foreach (var resource in Resources)
            if (!reference.SetEquals(resource.Value.Keys) || resource.Value.Any(pair => string.IsNullOrWhiteSpace(pair.Value)))
                throw new InvalidOperationException($"Invalid localization: {resource.Key}");
    }

